package checkifanumberisdivisibleby5;

public class CheckIfANumberIsDivisibleBy5 {
public static void main(String args[])
{
	int number_to_be_checked=11;
	if(number_to_be_checked %5 ==0) System.out.printf("Is the number %d divisible by 5? Yes",number_to_be_checked);
	else System.out.printf("Is the number %d divisible by 5? No",number_to_be_checked);
}
}
